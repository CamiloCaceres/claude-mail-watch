"""Copy watcher/mail_watch.py into hooks/watcher.ts.

A mod's hooks module can only import JavaScript, so the standalone watcher ships as a
string and runs as `python3 -`. Run this after every change to the watcher:

    python3 scripts/embed.py          # rewrite hooks/watcher.ts
    python3 scripts/embed.py --check  # exit 1 when hooks/watcher.ts is stale
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "watcher" / "mail_watch.py"
TARGET = ROOT / "hooks" / "watcher.ts"


def render() -> str:
    source = SOURCE.read_text(encoding="utf-8")
    return (
        "// Generated by scripts/embed.py from watcher/mail_watch.py. Do not edit by hand.\n"
        f"export const WATCHER_PY: string = {json.dumps(source)}\n"
    )


if __name__ == "__main__":
    wanted = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != wanted:
            print("hooks/watcher.ts is stale: run python3 scripts/embed.py", file=sys.stderr)
            sys.exit(1)
        print("hooks/watcher.ts is up to date")
    else:
        TARGET.parent.mkdir(exist_ok=True)
        TARGET.write_text(wanted, encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)}")
